import artwork from './characterArtwork.json'

type Artwork = { image: string; source: string }
type Biography = { paragraphs: string[]; source: { title: string; url: string } }

const artById: Partial<Record<string, Artwork>> = artwork

export function officialArtwork(archiveId?: number, siteId?: number | string) {
  return artById[String(archiveId)] ?? artById[`site:${siteId}`]
}

export function safePortrait(url = '') {
  return /^\/(?![/\\])|^https:\/\//i.test(url) ? url : ''
}

export function archivePortrait(id?: number, size: 'medium' | 'large' = 'medium') {
  return id ? `https://api.bgm.tv/v0/characters/${id}/image?type=${size}` : ''
}

const biographies = new Map<number, Biography>()

function addBiographies(title: string, url: string, entries: Record<number, string>) {
  for (const [id, text] of Object.entries(entries)) {
    biographies.set(Number(id), { paragraphs: text.split('\n'), source: { title, url } })
  }
}

